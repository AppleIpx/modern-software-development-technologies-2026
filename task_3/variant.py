# Вариант 4: результат теста.
# 0–49: Нужна доработка, 50–84: Зачёт, 85–100: Отличный результат.
score = int(input("Результат теста (0–100): "))

if score < 0 or score > 100:
    print("Ошибка диапазона")
elif score <= 49:
    print("Нужна доработка")
elif score <= 84:
    print("Зачёт")
else:
    print("Отличный результат")
